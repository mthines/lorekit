/**
 * `resolveFirstToken` owns the first-sign-in auto-mint decision for `/lore`'s
 * render. It replaces a bare `catch {}` that used to hide the production bug
 * (`token-mint.ts`'s header): these specs pin the decision table on its own,
 * with `mint` injected so no Supabase/Next mocking is needed.
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { resolveFirstToken } from './first-token';
import type { ApiToken } from './token-mint';

const EXISTING: ApiToken = {
  id: 'tok-existing',
  name: 'Old token',
  token_prefix: 'lk_rw_old...',
  permissions: ['read', 'write'],
  scopes: [],
  org_access: 'all',
  org_ids: [],
  last_used_at: null,
  created_at: '2025-01-01T00:00:00.000Z',
};

const MINTED: ApiToken = {
  id: 'tok-new',
  name: 'My first token',
  token_prefix: 'lk_rw_new...',
  permissions: ['read', 'write'],
  scopes: [],
  org_access: 'all',
  org_ids: [],
  last_used_at: null,
  created_at: '2026-01-01T00:00:00.000Z',
};

beforeEach(() => {
  vi.clearAllMocks();
});

describe('resolveFirstToken', () => {
  it('mints exactly once and returns the record + token when there are no existing tokens', async () => {
    const mint = vi.fn().mockResolvedValue({ token: 'lk_rw_abc', record: MINTED });

    const result = await resolveFirstToken({ existingTokens: [], autoGenerate: true, mint });

    expect(mint).toHaveBeenCalledTimes(1);
    expect(result).toEqual({ tokens: [MINTED], autoGeneratedToken: 'lk_rw_abc' });
  });

  it('does not mint when existing tokens are non-empty', async () => {
    const mint = vi.fn();

    const result = await resolveFirstToken({ existingTokens: [EXISTING], autoGenerate: true, mint });

    expect(mint).not.toHaveBeenCalled();
    expect(result).toEqual({ tokens: [EXISTING], autoGeneratedToken: null });
  });

  it('does not mint when autoGenerate is false', async () => {
    const mint = vi.fn();

    const result = await resolveFirstToken({ existingTokens: [], autoGenerate: false, mint });

    expect(mint).not.toHaveBeenCalled();
    expect(result).toEqual({ tokens: [], autoGeneratedToken: null });
  });

  it('degrades to existing tokens when the mint returns an error', async () => {
    const mint = vi.fn().mockResolvedValue({ error: 'cap reached' });

    const result = await resolveFirstToken({ existingTokens: [], autoGenerate: true, mint });

    expect(result).toEqual({ tokens: [], autoGeneratedToken: null });
  });

  it('degrades to existing tokens when the mint throws a non-Next error', async () => {
    const mint = vi.fn().mockRejectedValue(new Error('unexpected'));

    const result = await resolveFirstToken({ existingTokens: [EXISTING], autoGenerate: true, mint });

    expect(result).toEqual({ tokens: [EXISTING], autoGeneratedToken: null });
  });

  it('re-throws a Next control-flow error (redirect) rather than degrading', async () => {
    const redirectError = new Error('NEXT_REDIRECT');
    redirectError.name = 'NEXT_REDIRECT';
    // Mirrors Next's internal digest convention that `unstable_rethrow` keys off.
    (redirectError as unknown as { digest: string }).digest = 'NEXT_REDIRECT;replace;/login;307;';
    const mint = vi.fn().mockRejectedValue(redirectError);

    await expect(resolveFirstToken({ existingTokens: [], autoGenerate: true, mint })).rejects.toThrow(
      'NEXT_REDIRECT',
    );
  });
});
