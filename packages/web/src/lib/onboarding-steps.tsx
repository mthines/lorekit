import { Bot } from 'lucide-react';
import type { OnboardingStep } from './onboarding';
import { OnboardingStepContent } from '@/components/dashboard/OnboardingStepContent';
import { listTokens } from '@/lib/tokens';
import { mintToken } from '@/lib/token-mint';
import { resolveFirstToken } from '@/lib/first-token';
import { resolveMcpUrls } from '@/lib/mcp-url';
import { getKeyScopeCatalog } from '@/lib/key-scope-catalog';
import { SETTINGS_LANDING_HREF } from '@/lib/settings-routes';

/**
 * Build the onboarding steps (title, icon, and rendered content) on the server.
 *
 * Only the `connect` step belongs here. The GitHub webhook is an optional
 * enrichment — surfaced post-connect via `GithubAppTeaser`, not as a required
 * checklist step.
 *
 * Used by the `/lore` page (the app's home route). The `/learn/setup` page
 * has its own static tutorial layout and no longer calls this function.
 *
 * Completion state is NOT computed here — it lives in the
 * {@link OnboardingProvider}, which overlays server signals with the user's
 * manual "mark as done" choices.
 *
 * First login has no tokens: with `autoGenerateToken`, we mint a read+write
 * token so the user can copy a ready-to-use config with zero extra clicks.
 * The mint runs through `mintToken` (the `server-only` core in
 * `lib/token-mint.ts`), NOT `lib/tokens.ts`'s `'use server'` generate action —
 * a Server Component render must never call that action, because its success
 * path calls `revalidatePath`, which Next 15 forbids during render. This
 * render needs no revalidation anyway: it returns the freshly minted record
 * as `initialTokens` itself. `resolveFirstToken` (`lib/first-token.ts`) owns
 * the decision and degrades to "no auto token" on failure so the page still
 * renders.
 */
export async function buildOnboardingSteps(
  { autoGenerateToken = false }: { autoGenerateToken?: boolean } = {},
): Promise<OnboardingStep[]> {
  // Same catalog the Settings page passes, so the create form offers the same
  // choices in both places it renders. Fails soft to empty lists.
  //
  // Issued TOGETHER with the token list, not after it: the catalog reads scopes
  // and orgs and depends on nothing the token list returns — only the first-token
  // mint below does. Awaiting them in sequence made this a two-round-trip chain
  // on top of the `getVerifiedUser()` hop each one already waits for, which is
  // what turned `/lore`'s server render into a three-deep waterfall. This is the
  // same shape `settings/api-keys/page.tsx` already uses for the same pair.
  const [existingTokens, catalog] = await Promise.all([listTokens(), getKeyScopeCatalog()]);

  const { tokens, autoGeneratedToken } = await resolveFirstToken({
    existingTokens,
    autoGenerate: autoGenerateToken,
    mint: () => mintToken('My first token', ['read', 'write'], undefined, 'onboarding'),
  });

  const { mcpUrl } = resolveMcpUrls();

  return [
    {
      id: 'connect',
      title: 'Connect your agent',
      subtitle: 'Generate a token and add it to your .mcp.json file.',
      icon: <Bot className="size-4" />,
      content: (
        <OnboardingStepContent
          step="connect"
          mcpUrl={mcpUrl}
          initialTokens={tokens}
          autoGeneratedToken={autoGeneratedToken ?? undefined}
          manageHref={SETTINGS_LANDING_HREF}
          scopeCatalog={catalog.scopes}
          orgs={catalog.orgs}
        />
      ),
    },
  ];
}
