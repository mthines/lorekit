/**
 * The first-sign-in auto-mint decision for `/lore`'s onboarding render.
 *
 * Pulled out of `onboarding-steps.tsx` so it is a plain function a node-env
 * `.spec.ts` can exercise with an injected `mint` — the render itself must
 * never call a `'use server'` action whose success path revalidates (that is
 * the bug `lib/token-mint.ts` exists to fix), so this module only ever calls
 * the injected `mint`, never `generateToken`.
 *
 * Previously this decision lived inline behind a bare `catch {}`, which is
 * exactly what hid the production bug: the mint's `revalidatePath` call threw
 * during render, and the bare catch swallowed it along with every other kind
 * of failure, leaving an orphan `api_tokens` row and no token on screen.
 * `unstable_rethrow` restores the one distinction that catch erased — Next's
 * own control-flow errors (redirect, not-found, the dynamic-rendering bailout)
 * are not failures and must propagate, while a genuine mint failure degrades
 * to "no auto token" so the page still renders.
 */
import { unstable_rethrow } from 'next/navigation';
import type { ApiToken } from '@/lib/token-mint';

export interface ResolveFirstTokenArgs {
  /** Tokens the user already has, as read by `listTokens()`. */
  existingTokens: ApiToken[];
  /** Whether the caller wants a first-sign-in auto-mint at all. */
  autoGenerate: boolean;
  /** Injected effect — the render path passes `mintToken(..., 'onboarding')`. */
  mint: () => Promise<{ token: string; record: ApiToken } | { error: string }>;
}

export interface ResolveFirstTokenResult {
  /** `existingTokens` unchanged, or `[record]` when a mint just succeeded. */
  tokens: ApiToken[];
  /** The freshly minted token string, shown once, or `null`. */
  autoGeneratedToken: string | null;
}

export async function resolveFirstToken({
  existingTokens,
  autoGenerate,
  mint,
}: ResolveFirstTokenArgs): Promise<ResolveFirstTokenResult> {
  if (!autoGenerate || existingTokens.length > 0) {
    return { tokens: existingTokens, autoGeneratedToken: null };
  }

  try {
    const result = await mint();
    if ('token' in result) {
      return { tokens: [result.record], autoGeneratedToken: result.token };
    }
    // `{ error }` — already logged by `mintToken` itself. Degrade quietly.
    return { tokens: existingTokens, autoGeneratedToken: null };
  } catch (error) {
    // Next's own control-flow errors (redirect, not-found, the dynamic-
    // rendering bailout) are not mint failures and must propagate.
    unstable_rethrow(error);
    // Any other thrown error is a genuine, unexpected mint failure. `withSpan`
    // inside `mintToken` already logged it — degrade to no auto token so the
    // page still renders rather than taking down the whole route.
    return { tokens: existingTokens, autoGeneratedToken: null };
  }
}
